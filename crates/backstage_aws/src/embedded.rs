use crate::{Asset, Source};

macro_rules! asset {
    ($path:literal) => {
        asset!(
            $path,
            concat!("templates/full-automation/", $path),
            File,
            false
        )
    };
    ($path:literal, $source:expr, $kind:ident, $executable:literal) => {
        Asset {
            path: $path,
            source: Source::$kind(include_bytes!(concat!(
                env!("CARGO_MANIFEST_DIR"),
                "/../../",
                $source
            ))),
            executable: $executable,
        }
    };
}

